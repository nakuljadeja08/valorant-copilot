"""Fantasy store -> static JSON bundles for the game.

Same contract as `src/export/bundle.py`: no timestamps, sorted collections, so an unchanged
store re-exports to identical bytes and CI can diff the result. Four shapes, all under
`web/public/data/fantasy/`:

  season.json               calendar, brackets and results, teams, players, coaches, rules
  players/<event>.json      that event's prices and listed roles: the squad builder's pool
  points/<event>-w<n>.json  verified points per player and coach for one match week
  traces/<match_id>.json    every point on one map, down to the kills and rounds behind it
  rivals.json               simulated rival managers, so a league table works with no backend

Traces are compact JSON and index kills and players within the map, because the store's
lineage is ~48 MB as written. Nothing is dropped: `decode_refs` rebuilds the store's exact
references, and a test holds the two in agreement.

Only points the watchdog re-derives from raw rows are shipped. Anything else is listed under
`excluded` and the CLI exits non-zero, so CI cannot publish an unverified point.

Sim ground truth (team rating, player skill) is never exported: it would tell a manager
who is better than their price says.

Usage:
    python -m src.fantasy.season --seed 1337
    python -m src.fantasy.export                    # -> web/public/data/fantasy
"""

from __future__ import annotations

import argparse
import json
import random
import sqlite3
from pathlib import Path
from typing import Any

from src.export.bundle import dumps
from src.fantasy.balance import event_pool, random_squad
from src.fantasy.scoring import SCOPE, load_rules, rules_version
from src.fantasy.squads import score_week, validate_squad
from src.fantasy.store import open_store
from src.fantasy.verify import Mismatch, verify_points
from src.riot.resolve import ContentResolver, default_resolver, role_of

FANTASY_BUNDLE_VERSION = 1
DEFAULT_OUT = Path("web/public/data/fantasy")

# Whole directory, every file. Traces are fetched one map at a time, so this guards the
# repo and the deploy rather than a page load. Seed 1337 exports about a third of this.
SIZE_BUDGET_BYTES = 24 * 1024 * 1024

PROVENANCE_NOTE = "Simulated season — fictional teams and players, no real pro data"
PROVENANCE_DETAIL = (
    "Every team, player and coach is invented, and every match is generated by the in-repo "
    "simulator on the announced VCT 2027 calendar. Formats Riot has not published are "
    "marked as assumed. Real pro data needs rights that have not been granted, so none is "
    "used and nothing is scraped. Points are recomputed from the raw kill timeline before "
    "they are published."
)

_OWNED = ("season.json", "rivals.json", "players", "points", "traces")

# Rival managers per home region. They pick a fresh legal squad at each event from prices
# alone, with no hindsight, and keep it for the event: a plausible casual manager.
RIVALS_PER_REGION = 8
RIVAL_SEED = 2027
# Manager-style names, kept clear of the words pro team names use, so a rival can
# never be mistaken for a team.
_RIVAL_WORDS = (
    ("Midnight", "Static", "Granite", "Feral", "Northern", "Lucky", "Rusty", "Electric",
     "Sleepy", "Mighty", "Tiny", "Reckless"),
    ("Snipers", "Defusers", "Rotators", "Lurkers", "Peekers", "Planters", "Clutchers",
     "Flankers", "Eco Kings", "Op Hoarders", "Spike Carriers", "Entry Fraggers"),
)


def _compact(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":")) + "\n"


# ---------------------------------------------------------------- traces

def encode_refs(refs: list[dict[str, Any]], match_id: str, entity: str,
                kill_index: dict[tuple[int, int], int]) -> dict[str, list]:
    """Raw-row references in the compact trace form.

    Kills and this entity's assists become indexes into the map's kill list, rounds become
    round numbers. Anything else is kept verbatim under `other`.
    """
    out: dict[str, list] = {}
    for ref in refs:
        table, same_map = ref["table"], ref.get("match_id") == match_id
        if table == "round_kills" and same_map:
            out.setdefault("kills", []).append(kill_index[(ref["round_num"], ref["kill_ordinal"])])
        elif table == "round_kill_assists" and same_map and ref["assistant_puuid"] == entity:
            out.setdefault("assists", []).append(kill_index[(ref["round_num"], ref["kill_ordinal"])])
        elif table == "rounds" and same_map and "round_num" in ref:
            out.setdefault("rounds", []).append(ref["round_num"])
        else:
            out.setdefault("other", []).append(ref)
    return out


def decode_refs(rows: dict[str, list], trace: dict[str, Any], entity: str) -> list[dict[str, Any]]:
    """The inverse of `encode_refs`, given the trace file the rows came from."""
    match_id, kills = trace["match_id"], trace["kills"]
    refs: list[dict[str, Any]] = []
    for i in rows.get("kills", []):
        refs.append({"table": "round_kills", "match_id": match_id,
                     "round_num": kills[i][0], "kill_ordinal": kills[i][1]})
    for i in rows.get("assists", []):
        refs.append({"table": "round_kill_assists", "match_id": match_id,
                     "round_num": kills[i][0], "kill_ordinal": kills[i][1],
                     "assistant_puuid": entity})
    for n in rows.get("rounds", []):
        refs.append({"table": "rounds", "match_id": match_id, "round_num": n})
    refs.extend(rows.get("other", []))
    return refs


def _map_context(conn: sqlite3.Connection, match_id: str,
                 resolver: ContentResolver) -> dict[str, Any]:
    """The raw rows a map's points cite, small enough to ship with its trace."""
    players = conn.execute(
        """SELECT puuid, team_id AS side, character_id FROM match_players
           WHERE match_id = ? ORDER BY team_id, puuid""", (match_id,)).fetchall()
    index = {p["puuid"]: i for i, p in enumerate(players)}

    assists: dict[tuple[int, int], list[int]] = {}
    for a in conn.execute(
        """SELECT round_num, kill_ordinal, assistant_puuid FROM round_kill_assists
           WHERE match_id = ? ORDER BY round_num, kill_ordinal, assistant_puuid""", (match_id,)):
        assists.setdefault((a["round_num"], a["kill_ordinal"]), []).append(index[a["assistant_puuid"]])

    kills = [
        [k["round_num"], k["kill_ordinal"], index[k["killer_puuid"]], index[k["victim_puuid"]],
         assists.get((k["round_num"], k["kill_ordinal"]), [])]
        for k in conn.execute(
            """SELECT round_num, kill_ordinal, killer_puuid, victim_puuid FROM round_kills
               WHERE match_id = ? ORDER BY round_num, kill_ordinal""", (match_id,))
    ]
    rounds = [[r["round_num"], r["winning_team"]] for r in conn.execute(
        "SELECT round_num, winning_team FROM rounds WHERE match_id = ? ORDER BY round_num",
        (match_id,))]
    return {
        "players": [
            {"puuid": p["puuid"], "side": p["side"],
             "agent": resolver.agent_name(p["character_id"]), "role": role_of(p["character_id"])}
            for p in players
        ],
        "kills": kills,
        "rounds": rounds,
    }


def _points_by_map(conn: sqlite3.Connection) -> dict[str, dict[str, list[sqlite3.Row]]]:
    """match_id -> entity -> that entity's fantasy rows on the map, in name order."""
    out: dict[str, dict[str, list[sqlite3.Row]]] = {}
    for r in conn.execute(
        "SELECT match_id, name, value, inputs_json FROM features WHERE scope = ? ORDER BY match_id, name",
        (SCOPE,)):
        out.setdefault(r["match_id"], {}).setdefault(r["name"].partition(":")[2], []).append(r)
    return out


def _is_total(name: str) -> bool:
    return name.partition(":")[0] in ("fp_total", "fp_coach_total")


def build_trace(conn: sqlite3.Connection, series_map: sqlite3.Row, entities: dict[str, list[sqlite3.Row]],
                bad: set[tuple[str, str]], version: str, resolver: ContentResolver) -> dict[str, Any]:
    match_id = series_map["match_id"]
    trace: dict[str, Any] = {
        "trace_version": FANTASY_BUNDLE_VERSION,
        "match_id": match_id,
        "event_id": series_map["event_id"],
        "week_num": series_map["week_num"],
        "series_id": series_map["series_id"],
        "map_num": series_map["map_num"],
        "map_name": resolver.map_name(series_map["map_id"]),
        "teams": {"Red": series_map["red_team"], "Blue": series_map["blue_team"]},
        "winner": series_map["winner"],
        "rules_version": version,
        **_map_context(conn, match_id, resolver),
    }
    kill_index = {(k[0], k[1]): i for i, k in enumerate(trace["kills"])}

    points: dict[str, Any] = {}
    for entity, rows in sorted(entities.items()):
        if (match_id, entity) in bad:
            continue
        total = next(r["value"] for r in rows if _is_total(r["name"]))
        components = []
        for r in rows:
            if _is_total(r["name"]):
                continue
            head, *refs = json.loads(r["inputs_json"])
            if head.get("version") != version:
                raise SystemExit(f"{match_id} {r['name']} was scored under rules "
                                 f"{head.get('version')}, current are {version}")
            components.append({
                "rule": head["rule"], "count": head["count"], "points_each": head["points_each"],
                "value": r["value"], "rows": encode_refs(refs, match_id, entity, kill_index),
            })
        points[entity] = {"total": total, "components": components}
    trace["points"] = points
    return trace


# ---------------------------------------------------------------- season, prices, points

def _assumed(fmt: dict[str, Any], field: dict[str, Any]) -> bool:
    return bool(fmt.get("assumed") or field.get("assumed"))


def build_season(conn: sqlite3.Connection, rules: dict[str, Any],
                 resolver: ContentResolver) -> dict[str, Any]:
    maps_by_series: dict[str, list[dict[str, Any]]] = {}
    for m in conn.execute(
        """SELECT sm.series_id, sm.map_num, sm.match_id, sm.red_team, sm.blue_team, sm.winner, m.map_id
           FROM series_maps sm JOIN matches m ON m.match_id = sm.match_id
           ORDER BY sm.series_id, sm.map_num"""):
        maps_by_series.setdefault(m["series_id"], []).append({
            "map_num": m["map_num"], "match_id": m["match_id"],
            "map_name": resolver.map_name(m["map_id"]),
            "red_team": m["red_team"], "blue_team": m["blue_team"], "winner": m["winner"],
        })

    events = []
    for e in conn.execute("SELECT * FROM events ORDER BY ordinal").fetchall():
        eid = e["event_id"]
        fmt, field = json.loads(e["format_json"]), json.loads(e["field_json"])
        events.append({
            "event_id": eid, "ordinal": e["ordinal"], "name": e["name"], "kind": e["kind"],
            "starts_on": e["starts_on"], "ends_on": e["ends_on"],
            "cities": json.loads(e["cities_json"]), "format": fmt, "field": field,
            "assumed": _assumed(fmt, field),
            "budget": rules["squad"]["budget"][e["kind"]],
            "weeks": [dict(w) for w in conn.execute(
                "SELECT week_num, deadline_ms FROM match_weeks WHERE event_id = ? ORDER BY week_num",
                (eid,))],
            "entries": [dict(t) for t in conn.execute(
                """SELECT team_id, bracket, seed, placement, qualified_via FROM event_teams
                   WHERE event_id = ? ORDER BY bracket, seed, team_id""", (eid,))],
            "series": [
                {**{k: s[k] for k in s.keys() if k != "event_id"},
                 "maps": maps_by_series.get(s["series_id"], [])}
                for s in conn.execute(
                    "SELECT * FROM series WHERE event_id = ? ORDER BY scheduled_ms, series_id", (eid,))
            ],
        })

    sources = sorted(r[0] for r in conn.execute("SELECT DISTINCT source FROM matches"))
    return {
        "bundle_version": FANTASY_BUNDLE_VERSION,
        "provenance": {"note": PROVENANCE_NOTE, "detail": PROVENANCE_DETAIL,
                       "sources": sources, "fictional": True},
        "rules": rules,
        "rules_version": rules_version(rules),
        "regions": sorted(r[0] for r in conn.execute("SELECT DISTINCT region FROM pro_teams")),
        "teams": [dict(t) for t in conn.execute(
            "SELECT team_id, name, region, tier FROM pro_teams ORDER BY team_id")],
        "players": [dict(p) for p in conn.execute(
            "SELECT puuid, handle, region, base_role FROM pro_players ORDER BY puuid")],
        "coaches": [dict(c) for c in conn.execute(
            "SELECT coach_id, handle, team_id FROM pro_coaches ORDER BY coach_id")],
        "events": events,
    }


def build_players(conn: sqlite3.Connection, event: dict[str, Any],
                  previous_event: str | None) -> dict[str, Any]:
    """One event's pool. `bracket` limits a regional squad to its home region's teams."""
    brackets = {t["team_id"]: t["bracket"] for t in event["entries"]}
    previous = {} if previous_event is None else {
        r["entity_id"]: r["price"] for r in conn.execute(
            "SELECT entity_id, price FROM event_prices WHERE event_id = ?", (previous_event,))}
    handles = {r[0]: r[1] for r in conn.execute(
        "SELECT puuid, handle FROM pro_players UNION ALL SELECT coach_id, handle FROM pro_coaches")}

    pool = [
        {"entity_id": r["entity_id"], "kind": r["kind"], "handle": handles[r["entity_id"]],
         "team_id": r["team_id"], "bracket": brackets[r["team_id"]], "price": r["price"],
         "previous_price": previous.get(r["entity_id"]), "listed_role": r["listed_role"]}
        for r in conn.execute(
            "SELECT * FROM event_prices WHERE event_id = ? ORDER BY entity_id", (event["event_id"],))
    ]
    return {
        "bundle_version": FANTASY_BUNDLE_VERSION,
        "event_id": event["event_id"],
        "kind": event["kind"],
        "budget": event["budget"],
        "pool": pool,
    }


def build_week(event: dict[str, Any], week: dict[str, Any], traces: list[dict[str, Any]],
               kinds: dict[str, str], excluded: list[dict[str, str]], version: str) -> dict[str, Any]:
    """Points for one match week, summed from the traces so the two can never disagree.

    An entity who played no map that week is absent, which is what auto-sub reads.
    """
    entities: dict[str, dict[str, Any]] = {}
    for t in traces:
        for entity, p in t["points"].items():
            e = entities.setdefault(entity, {"kind": kinds[entity], "total": 0.0, "maps": [], "by_rule": {}})
            e["total"] += p["total"]
            e["maps"].append({"match_id": t["match_id"], "points": p["total"]})
            for c in p["components"]:
                e["by_rule"][c["rule"]] = e["by_rule"].get(c["rule"], 0.0) + c["value"]
    return {
        "bundle_version": FANTASY_BUNDLE_VERSION,
        "event_id": event["event_id"],
        "week_num": week["week_num"],
        "deadline_ms": week["deadline_ms"],
        "rules_version": version,
        "entities": entities,
        "excluded": excluded,
    }


def _rival_name(rng: random.Random, taken: set[str]) -> str:
    while True:
        name = f"{rng.choice(_RIVAL_WORDS[0])} {rng.choice(_RIVAL_WORDS[1])}"
        if name not in taken:
            taken.add(name)
            return name


def _rival_squad(rng: random.Random, pool: dict[str, dict[str, Any]], rules: dict[str, Any],
                 kind: str) -> dict[str, Any]:
    for _ in range(5000):
        squad = random_squad(rng, pool, rules)
        if not validate_squad(squad, pool, rules, kind):
            return squad
    raise SystemExit("could not draw a legal rival squad; check budgets against prices")


def build_rivals(conn: sqlite3.Connection, season: dict[str, Any],
                 week_points: dict[tuple[str, int], dict[str, float]],
                 rules: dict[str, Any]) -> dict[str, Any]:
    """Seeded rival managers with their squads and weekly scores, scored by `score_week`."""
    rng = random.Random(RIVAL_SEED)
    taken: set[str] = set()
    managers = [
        {"manager_id": f"rival-{region}-{i + 1}", "name": _rival_name(rng, taken), "region": region}
        for region in season["regions"] for i in range(RIVALS_PER_REGION)
    ]
    squads: dict[str, dict[str, Any]] = {}
    scores: dict[str, dict[str, float]] = {m["manager_id"]: {} for m in managers}
    for event in season["events"]:
        eid, kind = event["event_id"], event["kind"]
        pools = {b: event_pool(conn, eid, b) for b in {t["bracket"] for t in event["entries"]}}
        squads[eid] = {}
        for m in managers:
            bracket = "global" if kind == "international" else m["region"]
            squad = _rival_squad(random.Random(f"{RIVAL_SEED}:{m['manager_id']}:{eid}"),
                                 pools[bracket], rules, kind)
            squads[eid][m["manager_id"]] = {
                "starters": list(squad.starters), "subs": list(squad.subs),
                "coaches": list(squad.coaches), "captain": squad.captain, "vice": squad.vice,
            }
            for week in event["weeks"]:
                points = week_points.get((eid, week["week_num"]), {})
                scores[m["manager_id"]][f"{eid}-w{week['week_num']}"] =                     score_week(squad, points, rules)["total"]
    return {
        "bundle_version": FANTASY_BUNDLE_VERSION,
        "note": "Simulated rival managers: seeded squads picked from prices alone, no real people.",
        "managers": managers,
        "squads": squads,
        "scores": scores,
    }


# ---------------------------------------------------------------- export

def _clear(out_dir: Path) -> None:
    """Remove only what this exporter writes, so a dropped map can't leave a stale file."""
    if (out_dir / "index.json").exists():
        raise SystemExit(f"{out_dir} holds the coaching index; point --out at the fantasy directory")
    for name in _OWNED:
        path = out_dir / name
        if path.is_file():
            path.unlink()
        elif path.is_dir():
            for f in sorted(path.glob("*.json")):
                f.unlink()


def dir_size(out_dir: Path) -> int:
    return sum(f.stat().st_size for f in out_dir.rglob("*") if f.is_file())


def export(conn: sqlite3.Connection, out_dir: Path = DEFAULT_OUT,
           rules: dict[str, Any] | None = None) -> dict[str, Any]:
    rules = rules or load_rules()
    version = rules_version(rules)
    if not conn.execute("SELECT 1 FROM features WHERE scope = ? LIMIT 1", (SCOPE,)).fetchone():
        raise SystemExit("fantasy store has no points -- run `python -m src.fantasy.season` first")

    mismatches: list[Mismatch] = verify_points(conn, rules)
    bad = {(m.match_id, m.entity) for m in mismatches}
    resolver = default_resolver()

    season = build_season(conn, rules, resolver)
    kinds = {p["puuid"]: "player" for p in season["players"]}
    kinds |= {c["coach_id"]: "coach" for c in season["coaches"]}
    points = _points_by_map(conn)
    series_maps = conn.execute(
        """SELECT sm.*, s.event_id, s.week_num, m.map_id FROM series_maps sm
           JOIN series s ON s.series_id = sm.series_id JOIN matches m ON m.match_id = sm.match_id
           ORDER BY s.scheduled_ms, sm.series_id, sm.map_num""").fetchall()

    _clear(out_dir)
    for sub in ("players", "points", "traces"):
        (out_dir / sub).mkdir(parents=True, exist_ok=True)
    (out_dir / "season.json").write_text(dumps(season), encoding="utf-8")

    by_week: dict[tuple[str, int], list[dict[str, Any]]] = {}
    for sm in series_maps:
        trace = build_trace(conn, sm, points.get(sm["match_id"], {}), bad, version, resolver)
        (out_dir / "traces" / f"{sm['match_id']}.json").write_text(_compact(trace), encoding="utf-8")
        by_week.setdefault((sm["event_id"], sm["week_num"]), []).append(trace)

    week_points: dict[tuple[str, int], dict[str, float]] = {}
    previous = None
    for event in season["events"]:
        eid = event["event_id"]
        (out_dir / "players" / f"{eid}.json").write_text(
            dumps(build_players(conn, event, previous)), encoding="utf-8")
        previous = eid
        for week in event["weeks"]:
            traces = by_week.get((eid, week["week_num"]), [])
            maps = {t["match_id"] for t in traces}
            excluded = [{"match_id": m.match_id, "name": m.name, "reason": m.reason}
                        for m in mismatches if m.match_id in maps]
            built = build_week(event, week, traces, kinds, excluded, version)
            week_points[(eid, week["week_num"])] = {e: v["total"] for e, v in built["entities"].items()}
            (out_dir / "points" / f"{eid}-w{week['week_num']}.json").write_text(
                dumps(built), encoding="utf-8")

    (out_dir / "rivals.json").write_text(
        dumps(build_rivals(conn, season, week_points, rules)), encoding="utf-8")

    size = dir_size(out_dir)
    if size > SIZE_BUDGET_BYTES:
        raise SystemExit(f"fantasy bundles are {size / 2**20:.1f} MB, over the "
                         f"{SIZE_BUDGET_BYTES / 2**20:.0f} MB budget")
    return {"maps": len(series_maps), "weeks": len(by_week), "excluded": len(mismatches),
            "bytes": size, "out": str(out_dir)}


if __name__ == "__main__":
    from dotenv import load_dotenv
    load_dotenv()

    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="fantasy bundle directory")
    ap.add_argument("--db", default=None, help="store path (default: FANTASY_DB_PATH or data/fantasy.db)")
    args = ap.parse_args()

    result = export(open_store(args.db), Path(args.out))
    print(f"exported {result['maps']} map traces and {result['weeks']} match weeks, "
          f"{result['bytes'] / 2**20:.1f} MB -> {result['out']}")
    if result["excluded"]:
        raise SystemExit(f"{result['excluded']} fantasy rows failed verification and were left out")
